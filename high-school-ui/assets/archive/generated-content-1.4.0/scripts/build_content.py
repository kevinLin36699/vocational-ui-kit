#!/usr/bin/env python3
"""Generate the offline content catalog from its single JSON source."""
from pathlib import Path
import json
R=Path(__file__).resolve().parents[1]
d=json.loads((R/'data/generated-content-examples.json').read_text())
(R/'js/content-data.js').write_text('/* Generated by scripts/build_content.py; do not edit. */\nwindow.VocContentExamples='+json.dumps(d,ensure_ascii=False)+';\n')
print(len(d['contents']),'content examples generated')
